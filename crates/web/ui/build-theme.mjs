// Generates src/theme/tokens.css, tailwind.css and tokens.ts from src/theme/tokens.json,
// the same tokens.json the "Antre" design system artifact holds.
import { readFile, writeFile } from "node:fs/promises";

const dir = new URL("./src/theme/", import.meta.url);
const tokens = JSON.parse(await readFile(new URL("tokens.json", dir), "utf8"));
const banner = "/* Generated by build-theme.mjs from tokens.json. Do not edit by hand. */\n";

const [firstTheme, ...otherThemes] = tokens.color.themes.map((theme) => theme.id);
const perTheme = [...tokens.color.tokens, ...tokens.shadow.tokens];
const flat = ["spacing", "radius", "duration", "easing", "layer"].flatMap((family) => tokens[family].tokens);
const cssName = (name) => name.replaceAll(".", "\\.");
const decl = (name, value) => `  --${cssName(name)}: ${value};\n`;

function themeBlock(selector, theme) {
	const lines = perTheme.map((token) => decl(token.name, token.value[theme] ?? token.value[firstTheme])).join("");
	return `${selector} {\n  color-scheme: ${theme};\n${lines}}\n`;
}

let css = banner;
css += themeBlock(`:root,\n[data-theme="${firstTheme}"]`, firstTheme);
for (const theme of otherThemes) css += `\n${themeBlock(`[data-theme="${theme}"]`, theme)}`;
css += "\n:root {\n";
css += flat.map((token) => decl(token.name, token.value)).join("");
css += Object.entries(tokens.type.families)
	.map(([key, stack]) => decl(`font-${key}`, stack))
	.join("");
css += "}\n\n";
for (const group of tokens.type.groups) {
	for (const style of group.styles) {
		const family = style.family ?? group.family;
		const parts = [
			`font-family: var(--font-${family})`,
			`font-size: ${style.fontSize}`,
			`line-height: ${style.lineHeight}`,
			`font-weight: ${style.fontWeight}`,
		];
		if (style.letterSpacing) parts.push(`letter-spacing: ${style.letterSpacing}`);
		if (style.name === "overline") parts.push("text-transform: uppercase");
		css += `.an-type-${style.name} { ${parts.join("; ")}; }\n`;
	}
}
await writeFile(new URL("tokens.css", dir), css);

// Tailwind v4 mapping: utilities read the runtime variables, so theme switching needs no rebuild.
let tw = banner;
tw += "@theme inline {\n";
tw += tokens.color.tokens.map((token) => `  --color-${token.name}: var(--${token.name});\n`).join("");
tw += tokens.radius.tokens.map((token) => `  --radius-${token.name}: var(--${token.name});\n`).join("");
tw += tokens.shadow.tokens.map((token) => `  --shadow-${token.name}: var(--${token.name});\n`).join("");
tw += tokens.easing.tokens.map((token) => `  --${token.name}: var(--${token.name});\n`).join("");
for (const group of tokens.type.groups) {
	for (const style of group.styles) {
		tw += `  --text-${style.name}: ${style.fontSize};\n`;
		tw += `  --text-${style.name}--line-height: ${style.lineHeight};\n`;
		tw += `  --text-${style.name}--font-weight: ${style.fontWeight};\n`;
		if (style.letterSpacing) tw += `  --text-${style.name}--letter-spacing: ${style.letterSpacing};\n`;
	}
}
tw += "}\n";
// Font families go through @utility: an @theme --font-display would shadow the runtime --font-display.
for (const key of Object.keys(tokens.type.families)) {
	tw += `\n@utility font-${key} {\n  font-family: var(--font-${key});\n}\n`;
}
await writeFile(new URL("tailwind.css", dir), tw);

// Matches biome's formatting (tabs, 120 columns) so the output passes `biome check` unchanged.
const arrayLiteral = (constName, list) => {
	const items = list.map((token) => JSON.stringify(token.name));
	const oneLine = `export const ${constName} = [${items.join(", ")}] as const;`;
	if (oneLine.length <= 120) return oneLine;
	return `export const ${constName} = [\n\t${items.join(",\n\t")},\n] as const;`;
};
const ts = `// Generated by build-theme.mjs from tokens.json. Do not edit by hand.

${arrayLiteral("colorTokens", tokens.color.tokens)}

${arrayLiteral("spaceTokens", tokens.spacing.tokens)}

${arrayLiteral("radiusTokens", tokens.radius.tokens)}

${arrayLiteral("shadowTokens", tokens.shadow.tokens)}

export type ColorToken = (typeof colorTokens)[number];
export type SpaceToken = (typeof spaceTokens)[number];
export type RadiusToken = (typeof radiusTokens)[number];
export type ShadowToken = (typeof shadowTokens)[number];
export type ThemeToken = ColorToken | SpaceToken | RadiusToken | ShadowToken;
export type ThemeId = ${tokens.color.themes.map((theme) => JSON.stringify(theme.id)).join(" | ")};

export function tokenVar(name: ThemeToken): string {
\treturn \`var(--\${name.replaceAll(".", "\\\\.")})\`;
}
`;
await writeFile(new URL("tokens.ts", dir), ts);
