// Builds the static site published at the GitHub Pages org root: the landing page
// (EN at /, FR at /fr/), shared assets, install files and the docs under /docs/.
// See website/README.md for the deployment shape.
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const websiteDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoDir = path.resolve(websiteDir, "..");

export const DEFAULT_ORIGIN = "https://antre-ai.github.io";
const LOCALES = ["en", "fr"];

const FONT_PACKAGES = [
	{ pkg: "@fontsource-variable/geologica", family: "Geologica" },
	{ pkg: "@fontsource-variable/atkinson-hyperlegible-next", family: "Atkinson Hyperlegible Next" },
	{ pkg: "@fontsource-variable/atkinson-hyperlegible-mono", family: "Atkinson Hyperlegible Mono" },
];
const FONT_SUBSETS = new Set(["latin", "latin-ext"]);

const STATIC_FILES = [
	"favicon.svg",
	"favicon-512.png",
	"favicon-compact-512.png",
	"og-social.png",
	"og-social.jpg",
	"releases.json",
];
// Files that mention the site host; it is swapped for the custom domain when set.
const ORIGIN_FILES = ["llms.txt", ".well-known"];

/** Validates SITE_DOMAIN: a bare host name, never a URL or anything that could break out of HTML or CNAME. */
export function resolveOrigin(domain) {
	const value = (domain ?? "").trim().toLowerCase();
	if (!value) return { origin: DEFAULT_ORIGIN, cname: null };
	if (!/^(?=.{1,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/.test(value)) {
		throw new Error(`SITE_DOMAIN must be a bare host name like antre.example, got ${JSON.stringify(domain)}`);
	}
	return { origin: `https://${value}`, cname: value };
}

/** Replaces {{key}} with the locale string or a global; an unknown key is a build error. */
export function renderTemplate(template, strings, globals) {
	return template.replace(/\{\{([\w.]+)\}\}/g, (_, key) => {
		const value = strings[key] ?? globals[key];
		if (value === undefined) throw new Error(`Unknown template key: ${key}`);
		return String(value);
	});
}

/** Keeps the latin and latin-ext faces of a fontsource stylesheet, renamed to the token family and pointed at /fonts/. */
export function fontFaces(css, family) {
	const faces = [];
	for (const match of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)) {
		const [, name, block] = match;
		const subset = name.match(/-(latin-ext|latin)-wght-/)?.[1];
		if (!FONT_SUBSETS.has(subset)) continue;
		const file = block.match(/url\(\.\/files\/([\w.-]+\.woff2)\)/)?.[1];
		if (!file) continue;
		faces.push({
			file,
			css: block
				.replace(/font-family:\s*'[^']+'/, `font-family: '${family}'`)
				.replace(/url\(\.\/files\//, "url(/fonts/"),
		});
	}
	return faces;
}

async function exists(file) {
	try {
		await stat(file);
		return true;
	} catch {
		return false;
	}
}

const DEFAULT_HOST = new URL(DEFAULT_ORIGIN).host;

async function rewriteHost(file, origin) {
	const text = await readFile(file, "utf8");
	if (text.includes(DEFAULT_HOST)) await writeFile(file, text.replaceAll(DEFAULT_HOST, new URL(origin).host));
}

async function rewriteOrigin(target, origin) {
	if (origin === DEFAULT_ORIGIN) return;
	if ((await stat(target)).isFile()) return rewriteHost(target, origin);
	for (const entry of await readdir(target, { withFileTypes: true, recursive: true })) {
		if (entry.isFile()) await rewriteHost(path.join(entry.parentPath, entry.name), origin);
	}
}

async function buildFonts(outDir) {
	const fontsDir = path.join(outDir, "fonts");
	await mkdir(fontsDir, { recursive: true });
	const css = [];
	for (const { pkg, family } of FONT_PACKAGES) {
		const pkgDir = path.dirname(require.resolve(`${pkg}/package.json`));
		const styles = [await readFile(path.join(pkgDir, "wght.css"), "utf8")];
		if (await exists(path.join(pkgDir, "wght-italic.css"))) {
			styles.push(await readFile(path.join(pkgDir, "wght-italic.css"), "utf8"));
		}
		for (const face of styles.flatMap((style) => fontFaces(style, family))) {
			await cp(path.join(pkgDir, "files", face.file), path.join(fontsDir, face.file));
			css.push(face.css);
		}
	}
	return `/* Generated by build-site.mjs from @fontsource-variable packages (SIL OFL 1.1). */\n${css.join("\n\n")}\n`;
}

function notFoundPage() {
	return `<!doctype html>
<html lang="en" data-theme="dark">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex">
  <title>Page not found · Antre</title>
  <link rel="icon" href="/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="/assets/site.css">
  <script src="/assets/theme.js"></script>
</head>
<body>
  <main class="section"><div class="wrap">
    <p class="overline">404</p>
    <h1 class="section__title">This tunnel leads nowhere.</h1>
    <p class="lede">The page you are looking for is not in the lair. Try the <a href="/">home page</a> or the <a href="/docs/">documentation</a>.</p>
    <p class="lede" lang="fr">Cette page n'existe pas. Retournez à l'<a href="/fr/">accueil</a> ou à la <a href="/docs/">documentation</a>.</p>
  </div></main>
</body>
</html>
`;
}

export async function buildSite({
	outDir = path.join(websiteDir, "dist"),
	docsDir = path.join(repoDir, "docs", "dist"),
	domain = process.env.SITE_DOMAIN,
	requireDocs = false,
} = {}) {
	const { origin, cname } = resolveOrigin(domain);
	await rm(outDir, { recursive: true, force: true });
	await mkdir(path.join(outDir, "assets"), { recursive: true });

	const template = await readFile(path.join(websiteDir, "src", "index.html"), "utf8");
	const pkg = JSON.parse(await readFile(path.join(websiteDir, "package.json"), "utf8"));
	const version = process.env.GITHUB_SHA?.slice(0, 12) || pkg.version || "dev";
	for (const locale of LOCALES) {
		const strings = JSON.parse(await readFile(path.join(websiteDir, "src", "i18n", `${locale}.json`), "utf8"));
		const html = renderTemplate(template, strings, { site: origin, version });
		const pageDir = path.join(outDir, strings.path);
		await mkdir(pageDir, { recursive: true });
		await writeFile(path.join(pageDir, "index.html"), html);
	}

	await cp(path.join(websiteDir, "src", "assets"), path.join(outDir, "assets"), { recursive: true });
	await cp(
		path.join(repoDir, "crates", "web", "ui", "src", "theme", "tokens.css"),
		path.join(outDir, "assets", "tokens.css"),
	);
	await writeFile(path.join(outDir, "assets", "fonts.css"), await buildFonts(outDir));

	for (const file of STATIC_FILES) {
		await cp(path.join(websiteDir, file), path.join(outDir, file));
	}
	await cp(path.join(repoDir, "install.sh"), path.join(outDir, "install.sh"));
	for (const entry of ORIGIN_FILES) {
		await cp(path.join(websiteDir, entry), path.join(outDir, entry), { recursive: true });
	}
	for (const entry of ORIGIN_FILES) {
		await rewriteOrigin(path.join(outDir, entry), origin);
	}

	await writeFile(path.join(outDir, "404.html"), notFoundPage());
	await writeFile(path.join(outDir, "robots.txt"), `User-agent: *\nAllow: /\nSitemap: ${origin}/sitemap.xml\n`);
	await writeFile(
		path.join(outDir, "sitemap.xml"),
		`<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${["/", "/fr/", "/docs/"]
			.map((loc) => `  <url><loc>${origin}${loc}</loc></url>`)
			.join("\n")}\n</urlset>\n`,
	);
	// Without it GitHub Pages runs Jekyll, which drops dot-directories such as .well-known.
	await writeFile(path.join(outDir, ".nojekyll"), "");
	if (cname) await writeFile(path.join(outDir, "CNAME"), `${cname}\n`);

	if (await exists(path.join(docsDir, "index.html"))) {
		await cp(docsDir, path.join(outDir, "docs"), { recursive: true });
	} else if (requireDocs) {
		throw new Error(`Docs build not found at ${docsDir}; run "npm run build" in docs/ first`);
	} else {
		console.warn(`warning: no docs build at ${docsDir}, /docs/ will be missing`);
	}

	return { outDir, origin, cname };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const { outDir, origin, cname } = await buildSite({ requireDocs: process.argv.includes("--require-docs") });
	console.log(`Built ${origin} into ${path.relative(process.cwd(), outDir) || "."}${cname ? ` (CNAME ${cname})` : ""}`);
}
